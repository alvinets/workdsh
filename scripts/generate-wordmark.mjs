#!/usr/bin/env node
/**
 * Inline the HAOWISE wordmark PNG into a TypeScript module for workdsh-bundle.
 *
 * Plugin client code is compiled by plain `tsc` (no Vite), so `import logo from
 * './logo.png'` cannot resolve. Official client plugins embed images as data
 * URIs for the same reason, and the shell's `<link rel="icon">` hrefs are
 * rewritten at runtime, so a data URI is the only asset route available here.
 *
 * Keeping the PNG as a real file (rather than hand-pasted base64) means the
 * binary stays inspectable and re-generable; this script is the only place the
 * base64 exists.
 *
 * The upstream HAOWISE profile ships `HW_LIGHT` and `HW_DARK` as two constants,
 * but they are byte-identical (sha256 ae6426e9…) — one fixed-colour wordmark
 * served for both variants, so its light/dark CSS swap is a no-op. One asset.
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const assets = join(here, '..', 'packages', 'bundle', 'assets')
const target = join(assets, '..', 'src', 'client', 'wordmark.generated.ts')

const bytes = readFileSync(join(assets, 'haowise-wordmark.png'))
const digest = createHash('sha256').update(bytes).digest('hex').slice(0, 16)

writeFileSync(
	target,
	`/** Generated by scripts/generate-wordmark.mjs — do not edit. */\n\n`
	+ `/** HAOWISE wordmark, 363x96, ${bytes.length} bytes (sha256:${digest}). */\n`
	+ `export const HW_WORDMARK =\n\t'data:image/png;base64,${bytes.toString('base64')}'\n`,
)
console.log(`wordmark.generated.ts: 1 image, ${bytes.length} bytes -> ${readFileSync(target).length} bytes`)